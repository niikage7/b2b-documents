// Тексты документов для мока API: проект контракта, ТЗ-скан, извещение и шаблон длинного
// документа. Цитаты находок ищутся в тексте блока при сборке, поэтому смещения всегда верные.

import type { BlockKind, DocumentKind, FindingStatus, Level } from '../api/types';

export interface TemplateBlock {
  key?: string;
  kind: BlockKind;
  text: string;
  page: number;
  number?: string;
  level?: number;
  align?: 'left' | 'center' | 'right' | 'justify';
  bold?: boolean;
  table?: { id: number; row: number; col: number };
  lowOcr?: boolean;
}

export interface TemplateFinding {
  block: string;
  quote: string;
  rule: string;
  explanation: string;
  recommendation: string;
  confidence: number;
  status?: FindingStatus;
  decidedBy?: string;
  comment?: string;
  level?: Level;
}

export interface DocumentTemplate {
  kind: DocumentKind;
  pages: number;
  blocks: TemplateBlock[];
  findings: TemplateFinding[];
  ocrConfidence?: number;
  lowQualityPages?: number[];
}

const h = (number: string, text: string, page: number, key?: string): TemplateBlock => ({
  kind: 'heading', level: 1, number, text, page, key,
});
const p = (number: string, text: string, page: number, key?: string): TemplateBlock => ({
  kind: 'paragraph', number, text, page, key,
});
const t = (text: string, page: number, extra: Partial<TemplateBlock> = {}): TemplateBlock => ({
  kind: 'paragraph', text, page, ...extra,
});

