    """Пункты синтетического пакета (контракт, извещение, служебные) с полной разметкой, без заголовков."""
    from bench.samples import CONTRACT, FILLER, NOTICE

    out = []
    for item in [*CONTRACT, *NOTICE, *FILLER]:
        if item.level == 0:
            continue
        rules, also = next(((r, a) for prefix, (r, a) in PACKAGE_LABELS.items() if item.text.startswith(prefix)),
                           (set(), set()))
        out.append(Clause(item.text, frozenset(rules), frozenset(also)))
    return out
