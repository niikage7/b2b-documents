def _runs(text: str, bold: bool = False) -> str:
    rpr = FONT + ("<w:b/>" if bold else "")
    return r(escape(text), rpr)


def _table(rows: tuple[list[str], ...]) -> str:
    border = ('<w:tblBorders><w:top w:val="single" w:sz="4"/><w:left w:val="single" w:sz="4"/>'
              '<w:bottom w:val="single" w:sz="4"/><w:right w:val="single" w:sz="4"/>'
              '<w:insideH w:val="single" w:sz="4"/><w:insideV w:val="single" w:sz="4"/>'
              '</w:tblBorders>')
    cells = []
    for col in rows:
        inner = "".join(p(runs=_runs(text)) for text in col)
        cells.append('<w:tc><w:tcPr><w:tcW w:w="4500" w:type="dxa"/></w:tcPr>'
                     f"{inner}</w:tc>")
    return (f'<w:tbl><w:tblPr><w:tblW w:w="9000" w:type="dxa"/>{border}</w:tblPr>'
            f'<w:tr>{"".join(cells)}</w:tr></w:tbl>')


def _docx_body(title: str, items: list[Item], requisites: tuple[list[str], ...] | None) -> str:
    parts = [p(runs=_runs(title, True), ppr='<w:jc w:val="center"/>')]
    for item in items:
        rpr = "<w:b/>" if item.bold else ""
        ppr = numpr(1, item.level) if item.level >= 0 else '<w:jc w:val="both"/>'
        if item.level == 0:
            ppr += '<w:keepNext/><w:jc w:val="center"/>'
        parts.append(p(runs=_runs(item.text, item.bold), ppr=ppr))
    if requisites:
        parts.append(p(runs=_runs("Реквизиты и подписи сторон", True), ppr=numpr(1, 0)
                       + '<w:jc w:val="center"/>'))
        parts.append(_table(requisites))
    return "".join(parts)


_LIST = lvl(0, "decimal", "%1.") + lvl(1, "decimal", "%1.%2.") + lvl(2, "decimal", "%1.%2.%3.")


def build_docx(name: str, title: str, items: list[Item],
               requisites: tuple[list[str], ...] | None) -> Path:
    path = DOCX_DIR / f"{name}.docx"
    body = _docx_body(title, items, requisites)
    return make_docx(path, body, numbering_xml=numbering({0: _LIST}, {1: 0}))


def convert_pdf(docx: Path, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="lo-profile-") as profile:
        cmd = [
            "soffice", "--headless", "--norestore",
            f"-env:UserInstallation=file://{profile}",
            "--convert-to", "pdf:writer_pdf_Export",
            "--outdir", str(out_dir), str(docx),
        ]
        subprocess.run(cmd, check=True, capture_output=True, text=True)
    pdf = out_dir / f"{docx.stem}.pdf"
    if not pdf.exists():
        raise RuntimeError(f"LibreOffice не создал {pdf}")
    return pdf


def make_scan(pdf: Path, dst: Path, *, dpi: int = 200, seed: int = 0) -> Path:
    """Рендер PDF в картинки и сборка PDF только из изображений: текстового слоя нет."""
    dst.parent.mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)
    with tempfile.TemporaryDirectory(prefix="scan-pages-") as tmp:
        prefix = Path(tmp) / "page"
        subprocess.run(["pdftoppm", "-r", str(dpi), "-jpeg", "-jpegopt", "quality=82",
                        str(pdf), str(prefix)], check=True, capture_output=True, text=True)
        pages = sorted(Path(tmp).glob("page-*.jpg"),
                       key=lambda path: int(re.search(r"-(\d+)\.jpg$", path.name).group(1)))
        if not pages:
            raise RuntimeError(f"pdftoppm не создал страницы для {pdf}")
        images: list[Image.Image] = []
        generator = np.random.default_rng(seed)
        for page in pages:
            image = Image.open(page).convert("L")
            angle = rng.uniform(-0.45, 0.45)
            image = image.rotate(angle, resample=Image.Resampling.BICUBIC, expand=False,
                                 fillcolor=238)
            pixels = np.asarray(image, dtype=np.float32)
            noise = generator.normal(0, 3.2, pixels.shape)
            pixels = np.clip(pixels + noise, 0, 255).astype(np.uint8)
            images.append(Image.fromarray(pixels))
        images[0].save(dst, "PDF", resolution=float(dpi), save_all=True,
                       append_images=images[1:])
    return dst


