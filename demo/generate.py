def main() -> None:
    DOCX_DIR.mkdir(parents=True, exist_ok=True)
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    SCAN_DIR.mkdir(parents=True, exist_ok=True)
    validate_expected()

    docx_paths = {}
    for name, (title, items, requisites) in DOCUMENTS.items():
        docx_paths[name] = build_docx(name, title, items, requisites)
        print(f"docx: {docx_paths[name].relative_to(REPO)}")

    pdf_paths = {}
    for name, docx in docx_paths.items():
        pdf_paths[name] = convert_pdf(docx, PDF_DIR)
        print(f"pdf:  {pdf_paths[name].relative_to(REPO)}")

    scans = {}
    for name, pdf in pdf_paths.items():
        if name not in ("contract", "spec"):
            continue
        scans[name] = make_scan(pdf, SCAN_DIR / f"{name}.pdf", seed=sum(map(ord, name)))
        print(f"scan: {scans[name].relative_to(REPO)}")

    with zipfile.ZipFile(ROOT / "package.zip", "w", zipfile.ZIP_DEFLATED) as archive:
        for path in docx_paths.values():
            archive.write(path, path.name)
    with zipfile.ZipFile(ROOT / "package_scan.zip", "w", zipfile.ZIP_DEFLATED) as archive:
        for path in scans.values():
            archive.write(path, path.name)
    print("zip:  demo/package.zip, demo/package_scan.zip")

    (ROOT / "expected.json").write_text(
        json.dumps(EXPECTED, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "disputed.json").write_text(
        json.dumps(DISPUTED, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
